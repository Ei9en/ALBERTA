# Probe correlations
# ============================================================

def probe_correlations(
    rows: list[dict],
) -> dict:

    delta_kl = np.asarray(
        [
            row[
                "delta_kl"
            ]
            for row
            in rows
        ],
        dtype=np.float64,
    )

    delta_v = np.asarray(
        [
            row[
                "delta_v"
            ]
            for row
            in rows
        ],
        dtype=np.float64,
    )

    output = {}

    for feature_name in FEATURE_NAMES:

        if feature_name == "HU":

            values = np.asarray(
                [
                    row[
                        "H"
                    ]
                    * row[
                        "U"
                    ]
                    for row
                    in rows
                ],
                dtype=np.float64,
            )

        else:

            values = np.asarray(
                [
                    row[
                        feature_name
                    ]
                    for row
                    in rows
                ],
                dtype=np.float64,
            )

        output[
            feature_name
        ] = {
            "delta_kl_spearman":
                safe_spearman(
                    values,
                    delta_kl,
                ),

            "delta_v_spearman":
                safe_spearman(
                    values,
                    delta_v,
                ),
        }

    return output


