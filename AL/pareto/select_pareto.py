def make_feature_matrix(
    rows: list[dict],
) -> np.ndarray:

    return np.asarray(
        [
            [
                float(
                    row[
                        "H"
                    ]
                ),
                float(
                    row[
                        "U"
                    ]
                ),
                float(
                    row[
                        "H"
                    ]
                )
                * float(
                    row[
                        "U"
                    ]
                ),
            ]
            for row
            in rows
        ],
        dtype=np.float64,
    )


