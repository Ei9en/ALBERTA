#!/usr/bin/env python3

"""
ALBERTA - Dynamic Pareto Acquisition
====================================

Construct an Oracle queue using a learned two-objective local-response
surrogate.

This is the final stage of the dynamic Pareto acquisition pipeline:

    fixed human calibration probe
                |
                v
    contemporary local-response measurements
                |
                v
    (H, U, H*U)
        ->
    (Delta_KL, |Delta_V|)
                |
                v
    ExtraTrees response surrogate
                |
                v
    contemporary self-play pool
                |
                v
    predicted response space
                |
                v
    exact 2D non-dominated sorting
                |
                v
    crowding-distance truncation
                |
                v
    Oracle HMI queue

Scientific objective
--------------------

The acquisition criterion does NOT directly maximize H, U, HU or
the historical scalar score I.

Instead, H/U/HU are used as predictors of measured local learner
susceptibility:

    policy susceptibility:
        Delta_KL =
            KL(pi_before || pi_after)

    value susceptibility:
        Delta_V =
            |V_after - V_before|

The Pareto selector jointly maximizes the predicted magnitudes:

    maximize
        Delta_KL_hat
        Delta_V_hat

No scalarization of the two predicted response objectives is used.

Important interpretation
------------------------

The selected positions are predicted to induce large local changes
in both actor and critic.

This is response-based acquisition.

It does NOT imply that those changes point in a beneficial learning
direction, and Delta_V is deliberately a magnitude rather than an
Oracle-value improvement.

Input requirements
------------------

The probe-response file must have been generated by the canonical:

    AL/pareto/mesure_local_response.py

The candidate self-play pool must use the corrected uncertainty
estimator that excludes untrained BC value heads.

For both probe and pool data, HU is recomputed internally as:

    HU = H * U

rather than trusted from stored JSON.

Budget
------

The annotation budget preserves the historical ALBERTA definition:

    round(BUDGET_FRACTION * raw_pool_size)

with default:

    BUDGET_FRACTION = 0.0002 = 0.02%

The denominator is intentionally the raw self-play pool size,
before duplicate / legal-position / calibration-probe filtering.

Outputs
-------

Oracle queue:

    checkpoints/queue/oracle_queue_dynamic_pareto_<epoch>.jsonl

Acquisition diagnostics:

    data/pareto/pareto_selection_<epoch>.json
"""

