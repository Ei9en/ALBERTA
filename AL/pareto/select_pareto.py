def load_json_records(
    path: Path,
) -> list[dict]:

    if not path.exists():

        raise FileNotFoundError(
            f"File not found:\n{path}"
        )

    with path.open(
        "r",
        encoding="utf-8",
    ) as file:

        payload = json.load(
            file
        )

    if isinstance(
        payload,
        list,
    ):

        return payload

    if isinstance(
        payload,
        dict,
    ):

        for key in (
            "data",
            "records",
            "positions",
            "samples",
            "stats",
            "uncertainty_stats",
        ):

            value = payload.get(
                key
            )

            if isinstance(
                value,
                list,
            ):

                return value

    raise ValueError(
        f"Unsupported JSON structure:\n{path}"
    )


def load_jsonl(
    path: Path,
) -> list[dict]:

    if not path.exists():

        raise FileNotFoundError(
            f"File not found:\n{path}"
        )

    rows = []

    with path.open(
        "r",
        encoding="utf-8",
    ) as file:

        for line_number, line in enumerate(
            file,
            start=1,
        ):

            line = line.strip()

            if not line:
                continue

            try:

                row = json.loads(
                    line
                )

            except json.JSONDecodeError as exc:

                raise ValueError(
                    f"Invalid JSONL at line "
                    f"{line_number} in:\n{path}"
                ) from exc

            if not isinstance(
                row,
                dict,
            ):

                raise ValueError(
                    f"Expected JSON object at line "
                    f"{line_number} in:\n{path}"
                )

            rows.append(
                row
            )

    return rows


# ============================================================
# Probe response dataset
# ============================================================

def load_probe_dataset(
    path: Path,
    *,
    learner_epoch: int,
) -> list[dict]:
    """
    Load the dynamic local-response calibration dataset.

    HU is always recomputed as H * U.
    """

    rows = load_jsonl(
        path
    )

    cleaned = []

    for index, row in enumerate(
        rows
    ):

        for required in (
            "query_id",
            "fen",
            "H",
            "U",
            "delta_kl",
            "delta_v",
        ):

            if required not in row:

                raise ValueError(
                    f"Probe response {index} is missing "
                    f"'{required}'."
                )

        H = safe_float(
            row.get(
                "H"
            )
        )

        U = safe_float(
            row.get(
                "U"
            )
        )

        delta_kl = safe_float(
            row.get(
                "delta_kl"
            )
        )

        delta_v = safe_float(
            row.get(
                "delta_v"
            )
        )

        if (
            not np.isfinite(
                H
            )
            or not np.isfinite(
                U
            )
            or not np.isfinite(
                delta_kl
            )
            or not np.isfinite(
                delta_v
            )
        ):

            raise ValueError(
                f"Non-finite probe response at index {index}."
            )

        if U < 0.0:

            raise ValueError(
                f"Negative U at probe index {index}: {U}"
            )

        if (
            delta_kl < 0.0
            or delta_v < 0.0
        ):

            raise ValueError(
                "Pareto targets must be response magnitudes. "
                f"Probe index {index}: "
                f"delta_kl={delta_kl}, delta_v={delta_v}"
            )

        fen = row.get(
            "fen"
        )

        if (
            not isinstance(
                fen,
                str,
            )
            or not fen
        ):

            raise ValueError(
                f"Invalid FEN at probe index {index}."
            )

        chess.variant.AtomicBoard(
            fen
        )

        row_epoch = row.get(
            "learner_epoch"
        )

        if (
            row_epoch is not None
            and int(
                row_epoch
            ) != learner_epoch
        ):

            raise ValueError(
                "Probe-response epoch mismatch: "
                f"row {index} has learner_epoch={row_epoch}, "
                f"expected {learner_epoch}."
            )

        normalized = dict(
            row
        )

        normalized[
            "H"
        ] = H

        normalized[
            "U"
        ] = U

        normalized[
            "HU"
        ] = (
            H
            * U
        )

        normalized[
            "delta_kl"
        ] = delta_kl

        normalized[
            "delta_v"
        ] = delta_v

        cleaned.append(
            normalized
        )

    if len(
        cleaned
    ) < 20:

        raise RuntimeError(
            "Too few Pareto probe responses: "
            f"{len(cleaned)}."
        )

    return cleaned


